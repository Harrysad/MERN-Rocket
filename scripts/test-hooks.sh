#!/bin/sh
# Each case runs in a throw-away repository in a temp directory,
# so the real repository is never touched.

set -u

repo_root=$(cd "$(dirname "$0")/.." && pwd)
hooks_dir="$repo_root/.githooks"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

passed=0
failed=0

pass() {
  passed=$((passed + 1))
  printf 'PASS  %s\n' "$1"
}

fail() {
  failed=$((failed + 1))
  printf 'FAIL  %s\n' "$1"
  printf '      %s\n' "$2"
}

# check <description> <expected: ok|blocked> <actual: ok|blocked> <output file>
check() {
  if [ "$2" = "$3" ]; then
    pass "$1"
  else
    fail "$1" "expected $2, got $3: $(tail -n 1 "$4" 2>/dev/null)"
  fi
}

# new_repo <name> <branch>: fresh repository using the hooks under test.
new_repo() {
  dir="$work/$1"
  git init -q -b main "$dir"
  git -C "$dir" config user.name "Hook Test"
  git -C "$dir" config user.email "hook-test@example.invalid"
  git -C "$dir" config commit.gpgsign false
  git -C "$dir" config core.autocrlf false
  git -C "$dir" config core.hooksPath "$hooks_dir"
  git -C "$dir" symbolic-ref HEAD "refs/heads/$2"
  printf '%s\n' "$dir"
}

# repeat <count> <char>
repeat() {
  out=""
  i=0
  while [ "$i" -lt "$1" ]; do
    out="$out$2"
    i=$((i + 1))
  done
  printf '%s' "$out"
}

msg_repo=$(new_repo commit-msg test/branch)

# expect_msg <ok|blocked> <description> <message>
expect_msg() {
  printf '%s\n' "$3" > "$work/msg.txt"
  if git -C "$msg_repo" commit -q --allow-empty -F "$work/msg.txt" > "$work/out.txt" 2>&1; then
    actual=ok
  else
    actual=blocked
  fi
  check "commit-msg: $2" "$1" "$actual" "$work/out.txt"
}

scissors="# $(repeat 24 -) >8 $(repeat 24 -)"

expect_msg ok      "valid feat with scope"            "feat(backend): add health endpoint"
expect_msg ok      "breaking change marker"           "feat(api)!: change auth flow"
expect_msg blocked "unknown type"                     "feature: add x"
expect_msg blocked "missing colon"                    "fix add x"
expect_msg blocked "uppercase scope"                  "fix(Backend): add x"
expect_msg blocked "subject of 73 characters"         "chore: $(repeat 66 a)"
expect_msg ok      "subject of 72 characters"         "chore: $(repeat 65 a)"
expect_msg blocked "Co-Authored-By trailer"           "$(printf 'fix: x\n\nCo-Authored-By: Someone <a@b.c>')"
expect_msg blocked "co-authored-by in lowercase"      "$(printf 'fix: x\n\nco-authored-by: someone')"
expect_msg blocked "Co-Authored-By in a comment line" "$(printf 'fix: x\n# Co-Authored-By: someone')"
expect_msg blocked "AI attribution line"              "$(printf 'fix: x\n\nGenerated with Claude Code')"
expect_msg blocked "AI tool name in subject"          "docs: notes from ChatGPT"
expect_msg blocked "AI-generated marker"              "$(printf 'fix: x\n\nAI-generated change')"
expect_msg ok      "generated by a normal tool"       "chore: update files generated by openapi"
expect_msg ok      "merge commit"                     "Merge branch 'feature/x'"
expect_msg blocked "merge commit with AI trailer"     "$(printf "Merge branch 'x'\n\nCo-Authored-By: someone")"
expect_msg ok      "verbose diff below scissors"      "$(printf 'fix: x\n%s\ndiff --git a/x b/x\n+Co-Authored-By: someone' "$scissors")"

case_no=0
commit_path=$PATH

expect_staged() {
  case_no=$((case_no + 1))
  repo=$(new_repo "staged-$case_no" "$3")
  if [ -n "$4" ]; then
    mkdir -p "$repo/$(dirname "$4")"
    printf '%s\n' "$5" > "$repo/$4"
    git -C "$repo" add -- "$4"
  fi
  if PATH=$commit_path git -C "$repo" commit -q --allow-empty -m "test: case $case_no" > "$work/out.txt" 2>&1; then
    actual=ok
  else
    actual=blocked
  fi
  check "pre-commit: $2" "$1" "$actual" "$work/out.txt"
}

# Generated at runtime so this file never contains anything that looks like a real token.
token="ghp_$(LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 36)"

expect_staged ok      "regular file on a branch"     test/branch src/a.txt                      "hello"
expect_staged blocked "commit on main"               main        src/a.txt                      "hello"
expect_staged ok      "empty root commit on main"    main        ""                             ""
expect_staged blocked ".env file"                    test/branch backend/.env                   "PORT=8080"
expect_staged blocked ".env.local file"              test/branch .env.local                     "PORT=8080"
expect_staged ok      ".env.example with empty key"  test/branch backend/.env.example           "API_KEY="
expect_staged blocked ".env.example with a value"    test/branch backend/.env.example           "MAIL_API_KEY=abc123"
expect_staged ok      ".env.example non-secret"      test/branch backend/.env.example           "PORT=8080"
expect_staged blocked "CLAUDE.md"                    test/branch CLAUDE.md                      "x"
expect_staged blocked "nested CLAUDE.md"             test/branch backend/CLAUDE.md              "x"
expect_staged blocked ".claude directory"            test/branch .claude/settings.json          "{}"
expect_staged blocked "docs/superpowers"             test/branch docs/superpowers/plans/x.md    "x"
expect_staged blocked "AGENTS.md"                    test/branch AGENTS.md                      "x"
expect_staged blocked "copilot instructions"         test/branch .github/copilot-instructions.md "x"
expect_staged ok      "regular docs"                 test/branch docs/architecture.md           "# Architecture"
expect_staged blocked "secret in README"             test/branch README.md                      "GITHUB_TOKEN=$token"

commit_path=$(printf '%s' "$PATH" | tr ':' '\n' | grep -vxF "$(dirname "$(command -v gitleaks)")" | paste -sd: -)
expect_staged blocked "gitleaks not installed"       test/branch src/a.txt                      "hello"
commit_path=$PATH

repo=$(new_repo env-removal test/branch)
printf 'PORT=8080\n' > "$repo/.env"
git -C "$repo" add .env
git -C "$repo" commit -q --no-verify -m "test: seed"
git -C "$repo" rm -q --cached .env
if git -C "$repo" commit -q -m "test: remove env" > "$work/out.txt" 2>&1; then actual=ok; else actual=blocked; fi
check "pre-commit: removing a committed .env" ok "$actual" "$work/out.txt"

zeros=0000000000000000000000000000000000000000
sha=1111111111111111111111111111111111111111

# expect_push <ok|blocked> <description> <lines git passes on stdin>
# CRM_HOOK_TEST stops the hook from running this test suite again.
expect_push() {
  if printf '%s\n' "$3" | CRM_HOOK_TEST=1 sh "$hooks_dir/pre-push" origin url > "$work/out.txt" 2>&1; then
    actual=ok
  else
    actual=blocked
  fi
  check "pre-push: $2" "$1" "$actual" "$work/out.txt"
}

expect_push ok      "push a branch"           "refs/heads/feat/x $sha refs/heads/feat/x $zeros"
expect_push ok      "create main on remote"   "refs/heads/main $sha refs/heads/main $zeros"
expect_push blocked "update existing main"    "refs/heads/main $sha refs/heads/main $sha"
expect_push blocked "delete main"             "(delete) $zeros refs/heads/main $sha"
expect_push ok      "delete a branch"         "(delete) $zeros refs/heads/feat/x $sha"
expect_push blocked "main among several refs" "$(printf 'refs/heads/feat/x %s refs/heads/feat/x %s\nrefs/heads/main %s refs/heads/main %s' "$sha" "$zeros" "$sha" "$sha")"

printf '\n%s passed, %s failed\n' "$passed" "$failed"
[ "$failed" -eq 0 ]
